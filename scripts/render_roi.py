"""Render the large-model reference and cost comparison (pre-registration F5) from the artifacts.

python scripts/render_roi.py --out docs/RESULTS_ROI.md

Reads Qwen2.5-72B transcripts, comparisons, panel and helpfulness files in outputs/roi/, the
token count in outputs/roi/tokens_qwen72b.json, and Kaggle eval logs for Tiny Aya T4 time.
Prices are list prices with their source and date; they are inputs, not measurements.
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from htd.audit import wilson  # noqa: E402
from htd.helpful import helpful_rates  # noqa: E402
from htd.rule_checker import check_reply  # noqa: E402
from htd.sheet import load_sheet  # noqa: E402

PRICE_IN, PRICE_OUT = 0.36, 0.40  # USD per 1M tokens, Qwen2.5-72B-Instruct
PRICE_SRC = "OpenRouter model page, https://openrouter.ai/qwen/qwen-2.5-72b-instruct/api, read 2026-11-11 (lowest listed provider)"
T4_HOUR = 0.35  # USD per GPU-hour, GPU only, no VM
T4_SRC = "Google Cloud accelerator pricing, NVIDIA T4 on-demand GPU attachment, read 2026-11-11"


def read_jsonl(p: Path) -> list[dict]:
    return [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()]


def t4_hours_per_1000(log_globs: list[str]) -> tuple[float, int]:
    """GPU-hours per 1,000 dialogues: time between a generation command and the next command."""
    total = runs = 0
    for f in [p for g in log_globs for p in glob.glob(g)]:
        cmds = [(e["time"], e["data"]) for e in json.load(open(f)) if e.get("data", "").startswith("$ ")]
        for (t0, d), (t1, _) in zip(cmds, cmds[1:]):
            if "run_pilot.py" in d:
                total, runs = total + t1 - t0, runs + 1
    return total / (runs * 60) * 1000 / 3600, runs


def pct(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{100 * k / n:.1f}% [{100 * lo:.0f}, {100 * hi:.0f}]"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--roi", type=Path, default=Path("outputs/roi"))
    ap.add_argument("--logs", nargs="*", default=["outputs/kaggle-eval-2x2/*.log", "outputs/kaggle-eval-final/*.log"])
    ap.add_argument("--out", type=Path, default=Path("docs/RESULTS_ROI.md"))
    a = ap.parse_args()
    sheet = load_sheet()
    lines = ["# Large-model reference and cost (pre-registration F5)", "",
             "Generated by `scripts/render_roi.py` from `outputs/roi/` and the Kaggle eval logs. Qwen2.5-72B-Instruct "
             "through the Hugging Face inference API, plain prompt, temperature 0, at most 384 new tokens, on the same "
             "dialogues as Tiny Aya Fire. Descriptive only.", "",
             "## Retention (rule checker, turn 5)", "",
             "| split | Tiny Aya Fire base | Qwen2.5-72B | diff (points) [95% CI] | McNemar p |", "|---|---|---|---|---|"]
    for split in ("test", "heldout"):
        c = json.loads((a.roi / f"cmp_qwen72b_{split}.json").read_text())
        s = c["significance"]
        lines.append(f"| {split} | {100 * c['mean_a']:.1f}% | {100 * c['mean_b']:.1f}% | {100 * c['diff']:+.1f} "
                     f"[{100 * s['ci'][0]:+.1f}, {100 * s['ci'][1]:+.1f}] | {s['mcnemar_p']:.2g} |")
    lines += ["", "Per script, Qwen2.5-72B DR@5:", "", "| split | en | hi | hinglish |", "|---|---|---|---|"]
    for split in ("test", "heldout"):
        c = json.loads((a.roi / f"cmp_qwen72b_{split}.json").read_text())
        ps = c["per_script"]
        lines.append(f"| {split} | " + " | ".join(f"{100 * ps[k]['mean_b']:.0f}%" for k in ("en", "hi", "hinglish")) + " |")

    ref = read_jsonl(a.roi / "panel_reference.jsonl")
    agree = sum((r["judge_label"] == "PASS") == check_reply(r["reply"], sheet.product(r["product_id"]), sheet, r["script"]).all_present
                for r in ref)
    split_of = lambda r: "heldout" if "heldout" in r["dialogue_id"] else "test"  # noqa: E731
    panel_pass = {sp: sum(r["judge_label"] == "PASS" for r in ref if split_of(r) == sp) for sp in ("test", "heldout")}
    lines += ["", f"LLM panel check (majority of Llama-3.3-70B, DeepSeek-V3, gpt-oss-120b): the checker and the panel agree on "
              f"{agree} of {len(ref)} turn-5 replies; the panel passes {panel_pass['test']} of 60 test and "
              f"{panel_pass['heldout']} of 60 held-out replies.", ""]

    dev = sum(any("ऀ" <= ch <= "ॿ" for ch in rep) for r in read_jsonl(a.roi / "qwen72b_test.jsonl")
              if r["script"] == "en" for rep in r["replies"])
    lines += [f"Wrong script: {dev} of 100 replies to English test customers are written in Devanagari, although the system "
              "prompt asks for the customer's language and script.", ""]

    panels = [read_jsonl(a.roi / f"helpful_{n}.jsonl") for n in ("llama", "deepseek", "gptoss")]
    lines += ["## Helpfulness at turn 5 (LLM panel majority)", "", "| products | helpful [95% CI] |", "|---|---|"]
    for kind, flag in (("disclosure", True), ("control", False)):
        r = helpful_rates([[x for x in p if x["requires_disclosure"] == flag] for p in panels])["qwen72b"]
        lines.append(f"| {kind} | {pct(r['yes'], r['n'])} |")

    tok = json.loads((a.roi / "tokens_qwen72b.json").read_text())
    api = tok["M_in_per_1000_dialogues"] * PRICE_IN + tok["M_out_per_1000_dialogues"] * PRICE_OUT
    hours, runs = t4_hours_per_1000(a.logs)
    lines += ["", "## Cost per 1,000 five-turn dialogues", "",
              "| system | measured use | list price | cost |", "|---|---|---|---|",
              f"| Qwen2.5-72B, API | {tok['M_in_per_1000_dialogues']:.2f}M input + {tok['M_out_per_1000_dialogues']:.2f}M output tokens "
              f"(Qwen tokenizer, {tok['dialogues']} dialogues) | ${PRICE_IN}/M in, ${PRICE_OUT}/M out | ${api:.2f} |",
              f"| Tiny Aya Fire + LoRA, one T4 | {hours:.2f} GPU-hours (batch 8, no 4-bit, {runs} Kaggle runs of 60 dialogues) | "
              f"${T4_HOUR}/GPU-hour | ${hours * T4_HOUR:.2f} |", "",
              f"Prices: {PRICE_SRC}; {T4_SRC}. The T4 figure counts the GPU only, not the VM, and includes model loading per run.", ""]
    a.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
